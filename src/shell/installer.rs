//! Shell Installer

use anyhow::Result;
use std::fs;
use std::path::PathBuf;

use crate::config::Config;
use crate::shell::detector::DetectedShell;
use crate::shell::profiles::get_or_create_profile;

const SOMA_MARKER: &str = "# >>> soma >>>";
const SOMA_END_MARKER: &str = "# <<< soma <<<";

pub fn install(shell: &DetectedShell, config: &Config, force: bool, dry_run: bool) -> Result<()> {
    let profile_path = get_or_create_profile(shell)?;

    let content = generate_shell_config(shell, config)?;

    if dry_run {
        println!("Would write to: {}", profile_path.display());
        println!("--- Content ---");
        println!("{}", content);
        println!("--- End ---");
        return Ok(());
    }

    let existing = fs::read_to_string(&profile_path).unwrap_or_default();

    // Remove existing soma section if present
    let cleaned = remove_existing_soma(&existing);

    // Append new config
    let new_content = if cleaned.trim().is_empty() {
        format!("{}\n{}", cleaned.trim(), content)
    } else {
        format!("{}\n\n{}", cleaned.trim(), content)
    };

    fs::write(&profile_path, new_content)?;

    println!("✓ Installed to {}", profile_path.display());
    Ok(())
}

pub fn uninstall(shell: &DetectedShell, dry_run: bool) -> Result<()> {
    let profile_path = get_or_create_profile(shell)?;

    if !profile_path.exists() {
        println!("Profile not found: {}", profile_path.display());
        return Ok(());
    }

    let existing = fs::read_to_string(&profile_path)?;
    let cleaned = remove_existing_soma(&existing);

    if dry_run {
        println!("Would remove soma section from: {}", profile_path.display());
        return Ok(());
    }

    fs::write(&profile_path, cleaned)?;

    println!("✓ Uninstalled from {}", profile_path.display());
    Ok(())
}

fn remove_existing_soma(content: &str) -> String {
    let lines: Vec<&str> = content.lines().collect();
    let mut result = Vec::new();
    let mut in_soma_section = false;

    for line in lines {
        if line.trim() == SOMA_MARKER {
            in_soma_section = true;
            continue;
        }
        if line.trim() == SOMA_END_MARKER {
            in_soma_section = false;
            continue;
        }
        if !in_soma_section {
            result.push(line);
        }
    }

    // Trim trailing empty lines
    while result.last() == Some(&"") {
        result.pop();
    }

    result.join("\n")
}

fn generate_shell_config(shell: &DetectedShell, config: &Config) -> Result<String> {
    let alias = &config.shell.alias;
    let keybind = &config.shell.keybind;

    let config = match shell {
        DetectedShell::Pwsh => generate_pwsh_config(alias, keybind),
        DetectedShell::Bash => generate_bash_config(alias, keybind),
        DetectedShell::Zsh => generate_zsh_config(alias, keybind),
        DetectedShell::Fish => generate_fish_config(alias, keybind),
        DetectedShell::Cmd => generate_cmd_config(alias),
        DetectedShell::Unknown(_) => generate_generic_config(alias),
    };

    Ok(format!("{}\n{}\n{}", SOMA_MARKER, config, SOMA_END_MARKER))
}

fn generate_pwsh_config(alias: &str, keybind: &str) -> String {
    format!(
        r#"# soma - AI command assistant
# Auto-generated by `soma install`. Do not edit manually.

# Alias for quick ask
function {alias} {{
    param([string]$Query)
    if (-not $Query) {{ Write-Error "Usage: {alias} \"query\""; return }}
    soma ask $Query
}}
Set-Alias -Name {alias} -Value {alias} -Force

# Insert command on next line (Ctrl+Space)
function soma-insert {{
    $query = Read-Host "soma"
    if ($query) {{
        $cmd = soma insert $query
        if ($cmd) {{ [Microsoft.PowerShell.PSConsoleReadLine]::Insert("`n$cmd") }}
    }}
}}
Set-PSReadLineKeyHandler -Key '{keybind}' -Function soma-insert -Description "SOMA: Insert AI command" -ErrorAction SilentlyContinue

# Completions (if available)
if (Get-Command soma -ErrorAction SilentlyContinue) {{
    soma completions pwsh | Out-String | Invoke-Expression
}}

"#
    )
}

fn generate_bash_config(alias: &str, keybind: &str) -> String {
    format!(
        r#"# soma - AI command assistant
# Auto-generated by `soma install`. Do not edit manually.

# Alias for quick ask
alias {alias}='soma ask'

# Insert command on next line
_soma_insert() {{
    local query
    read -erp "soma> " query
    if [[ -n "$query" ]]; then
        local cmd=$(soma insert "$query")
        if [[ -n "$cmd" ]]; then
            READLINE_LINE="${READLINE_LINE}$'\n'$cmd"
            READLINE_POINT=${#READLINE_LINE}
        fi
    fi
}}
bind -x '"{keybind}": _soma_insert'

# Completions
if command -v soma &>/dev/null; then
    eval "$(soma completions bash)"
fi

"#
    )
}

fn generate_zsh_config(alias: &str, keybind: &str) -> String {
    format!(
        r#"# soma - AI command assistant
# Auto-generated by `soma install`. Do not edit manually.

# Alias for quick ask
alias {alias}='soma ask'

# Insert command on next line
_soma_insert() {{
    local query
    vared -p 'soma> ' query
    if [[ -n "$query" ]]; then
        local cmd=$(soma insert "$query")
        if [[ -n "$cmd" ]]; then
            LBUFFER+=$'\n'$cmd
            zle reset-prompt
        fi
    fi
}}
zle -N _soma_insert
bindkey '{keybind}' _soma_insert

# Completions
if command -v soma &>/dev/null; then
    eval "$(soma completions zsh)"
fi

"#
    )
}

fn generate_fish_config(alias: &str, keybind: &str) -> String {
    format!(
        r#"# soma - AI command assistant
# Auto-generated by `soma install`. Do not edit manually.

# Alias for quick ask
alias {alias}='soma ask'

# Insert command on next line
function _soma_insert
    set -l query (commandline -p "soma> ")
    if test -n "$query"
        set -l cmd (soma insert "$query")
        if test -n "$cmd"
            commandline -i "$cmd"
            commandline -f repaint
        end
    end
end
bind {keybind} _soma_insert

# Completions
if command -v soma >/dev/null
    soma completions fish | source
end

"#
    )
}

fn generate_cmd_config(alias: &str) -> String {
    format!(
        r#"@rem soma - AI command assistant
@rem Auto-generated by `soma install`. Do not edit manually.

@rem Alias for quick ask
doskey {alias}=soma ask $*

@rem Note: Ctrl+Space binding not available in cmd.exe
@rem Use `{alias} "your query"` instead

"#
    )
}

fn generate_generic_config(alias: &str) -> String {
    format!(
        r#"# soma - AI command assistant
# Auto-generated by `soma install`. Do not edit manually.

# Alias for quick ask
alias {alias}='soma ask'

# Note: Key binding not configured for unknown shell
# Use `{alias} "your query"` or `soma insert "your query"`

"#
    )
}
